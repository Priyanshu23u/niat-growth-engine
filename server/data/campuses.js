function getCampusById(id) {
  return NIAT_PARTNER_CAMPUSES.find((c) => c.id === id);
}

function searchCampuses(query = {}) {
  return NIAT_PARTNER_CAMPUSES.filter((campus) => {
    if (query.state && query.state !== "All" && campus.state !== query.state) return false;
    if (query.maxBudget && campus.totalAnnualFee > query.maxBudget) return false;
    if (query.minNatScore && campus.minNatPercentile > query.minNatScore) return false;
    if (query.keyword) {
      const kw = query.keyword.toLowerCase();
      const match =
        campus.name.toLowerCase().includes(kw) ||
        campus.city.toLowerCase().includes(kw) ||
        campus.state.toLowerCase().includes(kw) ||
        campus.specializations.some((s) => s.toLowerCase().includes(kw));
      if (!match) return false;
    }
    return true;
  });
}

module.exports = { NIAT_PARTNER_CAMPUSES, getCampusById, searchCampuses };
